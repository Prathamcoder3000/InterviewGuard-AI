const { test } = require('node:test')
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { stripTypeScriptTypes } = require('node:module')
const vm = require('node:vm')
const source = stripTypeScriptTypes(readFileSync('lib/candidate-evaluations.ts', 'utf8')).replace(/^export /gm, '')
const context = vm.createContext({})
vm.runInContext(source + '\nthis.api = { skillDistribution, reviewScore, upsertEvaluation };', context)
const { skillDistribution, reviewScore, upsertEvaluation } = context.api
const candidate = (id, score = 25) => ({ id, name: 'Same name', skills: ['Python', 'python', 'SQL', 'React', 'Go'], analysis: { risk_score: score, skill_analysis: [{ skill: 'Python', assessment: 'demonstrated' }, { skill: 'SQL', assessment: 'partial' }, { skill: 'React', assessment: 'unexpected' }] } })
test('counts duplicate claims once and preserves missing or unknown evidence', () => {
  const counts = skillDistribution(candidate('a'))
  assert.equal(counts.demonstrated, 1)
  assert.equal(counts.partial, 1)
  assert.equal(counts.insufficient_evidence, 2)
  assert.equal(counts.not_demonstrated, 0)
})
test('zero is a score; missing and invalid scores remain unassessed', () => {
  assert.equal(reviewScore(candidate('a', 0)), 0)
  for (const score of [null, NaN, Infinity, -1, 101]) assert.equal(reviewScore(candidate('a', score)), null)
})
test('same-name candidates remain distinct and edits replace only their stable ID', () => {
  const a = candidate('a'), b = candidate('b')
  const list = upsertEvaluation(upsertEvaluation([], a), b)
  assert.equal(list.length, 2)
  const updated = upsertEvaluation(list, candidate('a', 70))
  assert.equal(updated.length, 2)
  assert.equal(updated.find(c => c.id === 'a').analysis.risk_score, 70)
  assert.equal(updated.find(c => c.id === 'b').analysis.risk_score, 25)
})
